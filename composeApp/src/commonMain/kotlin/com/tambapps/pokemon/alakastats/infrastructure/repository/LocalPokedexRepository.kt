/** The Pokédex bundled with the app, read once and kept in memory */
class LocalPokedexRepository(
    private val json: Json,
) : PokedexRepository {

    private val mutex = Mutex()
    private var cache: Pokedex? = null

    override suspend fun getPokedex(): Either<GetPokemonDataError, Pokedex> = Either.catch {
        mutex.withLock {
            cache ?: load().also { cache = it }
        }
    }.mapLeft { GetPokemonDataError("Couldn't load the Pokédex", it) }

    private suspend fun load(): Pokedex {
        val text = Res.readBytes(POKEDEX_FILE).decodeToString()
        // a few hundred KB to parse and index: not on the main thread
        return withContext(Dispatchers.Default) {
            json.decodeFromString<PokedexEntity>(text).toDomain()
        }
    }
}

internal fun PokedexEntity.toDomain(): Pokedex {
    check(meta.schemaVersion == POKEDEX_SCHEMA_VERSION) {
        "The Pokédex file has the schema ${meta.schemaVersion}, this app reads the ${POKEDEX_SCHEMA_VERSION}"
    }
    val abilitiesById = abilities.associate { it.id to it.toDomain() }
    val movesById = moves.associate { it.id to it.toDomain() }
    val itemsById = items.associate { it.id to it.toDomain() }
    return Pokedex(
        formatId = meta.formatId,
        species = species.map { s ->
            PokedexSpecies(
                id = s.id,
                name = LocalizedName(s.name, s.nameFr),
                num = s.num,
                form = s.form,
                types = s.types.map(PokeType::valueOf),
                baseStats = s.baseStats.toPokeStats(),
                abilities = s.abilities.map { abilitiesById[it] ?: error("${s.id} refers to the unknown ability $it") },
                hiddenAbility = s.hiddenAbility?.let { abilitiesById[it] ?: error("${s.id} refers to the unknown ability $it") },
                baseSpecies = s.baseSpecies?.let(::PokemonName),
                isMega = s.isMega,
                megaOf = s.megaOf?.let(::PokemonName),
                megaStone = s.megaStone?.let { itemsById[it] ?: error("${s.id} refers to the unknown item $it") },
                weightKg = s.weightKg,
                cosmeticForms = s.cosmeticForms.map(::PokemonName),
                moves = s.moves.mapTo(LinkedHashSet()) { movesById[it] ?: error("${s.id} refers to the unknown move $it") },
            )
        },
        moves = movesById.values.toList(),
        abilities = abilitiesById.values.toList(),
        items = itemsById.values.toList(),
        types = types.map { PokedexType(PokeType.valueOf(it.id), LocalizedName(it.name, it.nameFr)) },
    )
}

private fun PokedexAbilityEntity.toDomain() = PokedexAbility(
    id = id,
    name = LocalizedName(name, nameFr),
    shortDesc = shortDesc,
    desc = desc,
    descFr = descFr,
    championsModified = championsModified,
)

private fun PokedexMoveEntity.toDomain() = PokedexMove(
    id = id,
    name = LocalizedName(name, nameFr),
    type = PokeType.valueOf(type),
    damageClass = DamageClass.valueOf(category),
    basePower = basePower,
    accuracy = accuracy,
    pp = pp,
    priority = priority,
    target = target,
    makesContact = makesContact,
    classifications = classifications.mapTo(LinkedHashSet(), MoveClassification::valueOf),
    shortDesc = shortDesc,
    desc = desc,
    descFr = descFr,
    championsModified = championsModified,
)

private fun PokedexItemEntity.toDomain() = PokedexItem(
    id = id,
    name = LocalizedName(name, nameFr),
    megaForms = megaForms.map(::PokemonName),
    shortDesc = shortDesc,
    desc = desc,
    descFr = descFr,
    championsModified = championsModified,
)

private fun PokedexBaseStatsEntity.toPokeStats() = PokeStats(
    hp = hp,
    attack = atk,
    defense = def,
    specialAttack = spa,
    specialDefense = spd,
    speed = spe,
)
